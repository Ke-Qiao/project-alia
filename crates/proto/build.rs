fn main() -> Result<(), Box<dyn std::error::Error>> {
    tonic_build::configure()
        .build_server(true)
        .build_client(true)
        .compile_protos(
            &[
                "proto/voice_session.proto",
                "proto/capture.proto",
                "proto/playback.proto",
                "proto/binding.proto",
                "proto/motion.proto",
                "proto/plugin.proto",
                "proto/settings.proto",
                "proto/sensor.proto",
            ],
            &["proto/"],
        )?;
    Ok(())
}
