// ========== Request/Response Types ==========

#[derive(Serialize, Deserialize, ToSchema)]
#[serde(deny_unknown_fields)]
pub struct ExecuteToolRequest {
    /// Non-nil UUID generated by the caller; retain it for retries of this operation.
    #[schema(format = Uuid)]
    pub request_id: Uuid,
    #[schema(min_length = 1, max_length = 128)]
    pub tool_name: String,
    /// JSON object, at most 16 KiB when encoded. Tool schema is validated by the adapter.
    #[schema(value_type = Object)]
    pub arguments: serde_json::Value,
    /// Optional model correlation label; changing this does not create a new effect.
    #[serde(default)]
    #[schema(max_length = 256)]
    pub call_id: Option<String>,
}

#[derive(Serialize, Deserialize)]
pub struct OpenAIFunctionsResponse {
    pub tools: Vec<serde_json::Value>,
}

// ========== Handlers ==========

/// List all available tools
async fn list_tools(
    State(state): State<AppState>,
    auth: AuthUser,
) -> Result<Json<Vec<ToolDefinition>>> {
    let tools = state.modules.tools.list_tools_for(auth.id).await?;
    Ok(Json(tools))
}

/// Get tools in OpenAI function calling format
async fn list_tools_openai_format(
    State(state): State<AppState>,
    auth: AuthUser,
) -> Result<Json<OpenAIFunctionsResponse>> {
    let tools = state.modules.tools.list_tools_for(auth.id).await?;
    let openai_tools = to_openai_functions(&tools);
    Ok(Json(OpenAIFunctionsResponse {
        tools: openai_tools,
    }))
}

/// Propose a durable effect. A successful HTTP response acknowledges the ledger;
/// inspect status/completion before claiming that the tool actually succeeded.
#[utoipa::path(post, path = "/api/v1/tools/execute", tag = "execution", security(("bearer" = [])),
    request_body = ExecuteToolRequest, responses(
        (status = 200, description = "Durable effect created or identical request replayed", body = EffectRecord),
        (status = 400, description = "Invalid JSON, UUID, arguments or missing implementation revision", body = super::effects::ExecutionErrorResponse),
        (status = 401, description = "Authentication required"),
        (status = 403, description = "Current owner or tool policy does not authorize execution", body = super::effects::ExecutionErrorResponse),
        (status = 409, description = "Request identity reused for another intent or service stopping", body = super::effects::ExecutionErrorResponse),
        (status = 429, description = "Proposal or dispatch capacity reached", body = super::effects::ExecutionErrorResponse),
        (status = 503, description = "Execution acknowledgement unavailable; retain request_id", body = super::effects::ExecutionErrorResponse)
    ))]
pub async fn execute_tool(
    State(state): State<AppState>,
    auth: AuthUser,
    body: std::result::Result<Json<ExecuteToolRequest>, JsonRejection>,
) -> std::result::Result<Json<EffectRecord>, ExecutionApiError> {
    let source_received_at = chrono::Utc::now();
    let source_privacy_epoch =
        crate::modules::memory::source::capture_source_epoch(&state.db, auth.id)
            .await
            .map_err(|error| {
                crate::modules::execution::types::ExecutionError::Database(sea_orm::DbErr::Custom(
                    format!("source admission unavailable: {error:#}"),
                ))
            })?;
    let Json(body) = body?;
    let call = ToolCall {
        tool_name: body.tool_name,
        arguments: body.arguments,
        call_id: body.call_id.unwrap_or_else(|| body.request_id.to_string()),
    };

    let ctx = ToolContext {
        context_id: None,
        user_id: auth.id,
        request_id: body.request_id,
        source_received_at,
        source_event_id: None,
        source_privacy_epoch: Some(source_privacy_epoch),
        invocation_key: "0".into(),
        conversation_id: None,
        source: "manual".to_string(),
        channel_id: None,
        cancel: None,
    };

    let result = state.execution.submit(call, &ctx).await?;
    Ok(Json(result))
}

/// Get a specific tool definition
async fn get_tool(
    State(state): State<AppState>,
    auth: AuthUser,
    axum::extract::Path(name): axum::extract::Path<String>,
) -> Result<Json<ToolDefinition>> {
    state
        .modules
        .tools
        .list_tools_for(auth.id)
        .await?
        .into_iter()
        .find(|tool| tool.name.as_str() == name)
        .map(Json)
        .ok_or_else(|| crate::error::AppError::NotFound(format!("Tool '{}' not found", name)))
}

/// MCP manages configured services only; executable paths/endpoints and
/// credentials cannot be supplied by an API request or a model argument.
async fn list_mcp(
    State(state): State<AppState>,
    auth: AuthUser,
) -> Result<Json<Vec<crate::tools::mcp::McpStatus>>> {
    super::plugins::require_admin(&auth)?;
    super::plugins::require_current_actor(&state.db, &auth, true, false).await?;
    Ok(Json(state.mcp.statuses().await))
}
async fn restart_mcp(
    State(state): State<AppState>,
    auth: AuthUser,
    axum::extract::Path(id): axum::extract::Path<String>,
) -> Result<Json<serde_json::Value>> {
    mutate_mcp(state, auth, id, true).await
}
async fn stop_mcp(
    State(state): State<AppState>,
    auth: AuthUser,
    axum::extract::Path(id): axum::extract::Path<String>,
) -> Result<Json<serde_json::Value>> {
    mutate_mcp(state, auth, id, false).await
}

async fn mutate_mcp(
    state: AppState,
    auth: AuthUser,
    id: String,
    restart: bool,
) -> Result<Json<serde_json::Value>> {
    use crate::error::AppError;
    super::plugins::require_admin(&auth)?;
    let (reply, response) = tokio::sync::oneshot::channel();
    let db = state.db.clone();
    let manager = state.mcp.clone();
    // The original runtime owner survives an HTTP disconnect. Hold the current
    // actor row lock through publication so a revoked admin cannot start a host.
    state
        .runtime_tasks
        .try_spawn("mcp_management", async move {
            let result: Result<serde_json::Value> = async {
                let tx = db.begin().await?;
                super::plugins::require_current_actor(&tx, &auth, true, true).await?;
                if restart {
                    manager.restart(&id).await?;
                } else {
                    manager.stop(&id).await?;
                }
                tx.commit().await?;
                Ok(serde_json::json!({"id":id,"state":if restart {"connecting"} else {"stopped"}}))
            }
            .await;
            let _ = reply.send(result);
            Ok(())
        })
        .map_err(|_| AppError::Unavailable("server runtime is stopping"))?;
    response
        .await
        .map_err(|_| {
            AppError::Unavailable(
                "MCP operation owner failed; inspect service state before retrying",
            )
        })?
        .map(Json)
}

// ========== Routes ==========

pub fn routes() -> Router<AppState> {
    Router::new()
        .route("/tools/mcp/services", get(list_mcp))
        .route("/tools/mcp/services/{id}/restart", post(restart_mcp))
        .route("/tools/mcp/services/{id}/stop", post(stop_mcp))
        .route("/tools", get(list_tools))
        .route("/tools/openai", get(list_tools_openai_format))
        .route("/tools/{name}", get(get_tool))
        .route("/tools/execute", post(execute_tool))
}
