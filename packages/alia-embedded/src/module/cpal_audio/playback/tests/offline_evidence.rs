fn stream(bus: &AudioReferenceBus, direction: AudioDirection) -> AudioStreamClock {
    bus.open_stream(
        direction,
        AudioFormat {
            sample_rate_hz: 16000,
            channels: 2,
        },
    )
}

fn capture(clock: &mut AudioStreamClock, pcm: &[i16]) {
    let reading = clock.probe.unknown_clock();
    observe_capture_samples(clock, pcm, reading, AudioSampleBoundary::CpalInputCallback);
}

fn output(clock: &mut AudioStreamClock, buffer: &Mutex<PlaybackBuffer>, pcm: &mut [i16]) {
    let reading = clock.probe.unknown_clock();
    fill_output_buffer(pcm, buffer, clock, reading);
}

fn submit(sender: &PlaybackSender, owner: &Arc<AudioSubmission>, pcm: &[i16]) {
    assert!(sender.submit(owner, 0, pcm, false).unwrap());
    assert!(sender.submit(owner, pcm.len() as u64, &[], true).unwrap());
}

fn cue(sender: &PlaybackSender, voice: &AudioSubmission) -> Arc<AudioSubmission> {
    sender
        .open_cue_submission(
            PlaybackIdentity {
                scope: voice.identity.scope,
                playback_id: uuid::Uuid::from_u128(200),
                playback_sequence: 1,
            },
            16000,
            voice.generation,
        )
        .unwrap()
}

fn round_trip(session: EvidenceSession) -> AudioEvidence {
    let mut observed = session.finish().unwrap();
    // Inputs are generated by this test even though capture and output travel
    // through the real production callback helpers. No native device was open.
    observed.source = EvidenceSource::SyntheticFixture;
    let mut bytes = Vec::new();
    observed
        .write_json(
            &mut bytes,
            EvidenceLimits::default(),
            &CancellationToken::new(),
        )
        .unwrap();
    let decoded = AudioEvidence::read_json(
        bytes.as_slice(),
        EvidenceLimits::default(),
        &CancellationToken::new(),
    )
    .unwrap();
    assert_eq!(
        serde_json::to_value(&decoded).unwrap(),
        serde_json::to_value(&observed).unwrap()
    );
    assert_eq!(decoded.source, EvidenceSource::SyntheticFixture);
    assert!(decoded.unobserved_history_possible);
    assert_eq!(decoded.discarded_records, 0);
    assert_eq!(decoded.discarded_samples, 0);
    decoded
}

fn replay_samples(evidence: &AudioEvidence, direction: AudioDirection) -> Vec<f64> {
    evidence
        .replay(EvidenceLimits::default())
        .unwrap()
        .filter(|step| step.record.timing.stream.direction == direction)
        .flat_map(|step| step.record.samples())
        .collect()
}

fn cleanup(
    sender: &PlaybackSender,
    receiver: &PlaybackReceiver,
    renderer: &mut Renderer,
    buffer: &Mutex<PlaybackBuffer>,
    owners: &[&Arc<AudioSubmission>],
) {
    sender.shutdown();
    buffer.lock().unwrap().clear();
    renderer.clear();
    assert!(matches!(
        receiver.take(true),
        Some(PlaybackAction::Shutdown)
    ));
    assert!(sender.begin().is_err());
    assert_eq!(sender.0.0.source_bytes.load(Ordering::Acquire), 0);
    assert!(sender.0.0.lock().media.is_empty());
    assert_eq!(buffer.lock().unwrap().len(), 0);
    assert!(renderer.current.iter().all(Option::is_none));
    for owner in owners {
        assert!(owner.output_quiescent());
        assert!(owner.snapshot(100).observation_end.is_some());
        assert_eq!(owner.snapshot(101).presented_source_frames, None);
    }
}

#[test]
fn capture_mix_exact_cancel_and_single_observer_round_trip_the_actual_pcm() {
    let bus = AudioBus::new(2).reference();
    let mut session =
        EvidenceSession::start(&bus, EvidenceLimits::default(), CancellationToken::new()).unwrap();
    assert!(bus.clone().try_claim_reader().is_none());
    assert!(
        EvidenceSession::start(&bus, EvidenceLimits::default(), CancellationToken::new()).is_err()
    );
    let mut capture_clock = stream(&bus, AudioDirection::Capture);
    let mut playback_clock = stream(&bus, AudioDirection::Playback);
    let captured: Vec<_> = (0..2052)
        .map(|n| if n % 2 == 0 { 8192 } else { -8192 })
        .collect();
    capture(&mut capture_clock, &captured);

    let (sender, receiver) = channel(8);
    let generation = sender.begin().unwrap();
    let voice = identified(&sender, &receiver, 1, generation);
    let cue = cue(&sender, &voice);
    submit(&sender, &voice, &[10000, 20000, 30000]);
    submit(&sender, &cue, &[5000, 5000, 5000]);
    let mut renderer = Renderer::default();
    let mut buffer = PlaybackBuffer::new(receiver.generation());
    render_pending(&receiver, &mut renderer, &mut buffer);
    let buffer = Mutex::new(buffer);
    let mut mixed = [0; 2];
    output(&mut playback_clock, &buffer, &mut mixed);
    assert_eq!(mixed, [11000; 2]);
    assert!(sender.cancel_submission(&cue, "offline exact cue cancellation"));
    let mut voice_tail = [0; 4];
    output(&mut playback_clock, &buffer, &mut voice_tail);
    assert_eq!(voice_tail, [20000, 20000, 30000, 30000]);
    assert_eq!(voice.snapshot(1).submitted_source_frames, Some(3));
    assert_eq!(
        voice.snapshot(2).observation_end,
        Some(ObservationEnd::SubmissionFinished)
    );
    assert_eq!(cue.snapshot(1).submitted_source_frames, Some(1));
    assert!(matches!(
        cue.snapshot(2).observation_end,
        Some(ObservationEnd::Cancelled { .. })
    ));

    capture_clock.probe.close();
    playback_clock.probe.close();
    session.pump(32).unwrap();
    let evidence = round_trip(session);
    assert_eq!(
        replay_samples(&evidence, AudioDirection::Capture),
        captured
            .iter()
            .map(|&s| f64::from(s) / 32768.0)
            .collect::<Vec<_>>()
    );
    assert_eq!(
        replay_samples(&evidence, AudioDirection::Playback),
        mixed
            .into_iter()
            .chain(voice_tail)
            .map(|s| f64::from(s) / 32768.0)
            .collect::<Vec<_>>()
    );
    let capture_records: Vec<_> = evidence
        .records
        .iter()
        .filter(|r| r.timing.stream.direction == AudioDirection::Capture && r.timing.frames > 0)
        .collect();
    assert_eq!(
        capture_records
            .iter()
            .map(|r| (r.timing.start_frame, r.timing.frames))
            .collect::<Vec<_>>(),
        [(0, 512), (512, 512), (1024, 2)]
    );
    assert!(capture_records.iter().all(|r| r.boundary
        == Some(AudioSampleBoundary::CpalInputCallback)
        && r.sample_format == Some(NativeSampleFormat::I16)));
    for record in &evidence.records {
        assert_eq!(record.timing.clock.quality, AudioTimeQuality::Unknown);
        assert_eq!(record.timing.clock.sample_ns, None);
        assert_eq!(record.timing.clock.queued_frames, None);
    }
    let capture_final = evidence.observed_latest.capture.as_ref().unwrap();
    let playback_final = evidence.observed_latest.playback.as_ref().unwrap();
    assert_ne!(
        capture_final.stream.stream_id,
        playback_final.stream.stream_id
    );
    assert_eq!(capture_final.cursor, 1026);
    assert_eq!(playback_final.cursor, 3);
    for final_state in [capture_final, playback_final] {
        assert!(final_state.closed);
        assert_eq!(final_state.lost_blocks, 0);
        assert_eq!(final_state.lost_frames, 0);
    }
    cleanup(&sender, &receiver, &mut renderer, &buffer, &[&voice, &cue]);
    assert!(bus.try_claim_reader().unwrap().try_read().is_none());
}

#[test]
fn explicit_hold_records_real_silence_and_resume_retains_only_voice_tail() {
    let bus = AudioBus::new(2).reference();
    let mut session =
        EvidenceSession::start(&bus, EvidenceLimits::default(), CancellationToken::new()).unwrap();
    let mut capture_clock = stream(&bus, AudioDirection::Capture);
    let mut playback_clock = stream(&bus, AudioDirection::Playback);
    capture(&mut capture_clock, &[8192, -8192]);
    let (sender, receiver) = channel(8);
    let generation = sender.begin().unwrap();
    let voice = identified(&sender, &receiver, 1, generation);
    let cue = cue(&sender, &voice);
    submit(&sender, &voice, &[10000, 20000]);
    submit(&sender, &cue, &[5000, 5000]);
    let mut renderer = Renderer::default();
    let mut buffer = PlaybackBuffer::new(receiver.generation());
    render_pending(&receiver, &mut renderer, &mut buffer);
    let buffer = Mutex::new(buffer);
    let control = voice.control().unwrap();
    control.observe_capture(0, true).unwrap();
    let pause = ControlCommand {
        scope: voice.identity.scope,
        hold_id: uuid::Uuid::from_u128(300),
        command_id: uuid::Uuid::from_u128(301),
        sequence: 1,
        action: ControlAction::Pause {
            reason: HoldReason::ExplicitWait,
            through_sequence: 0,
            budget_ms: 3000,
        },
    };
    assert_eq!(
        sender
            .apply_control(control, &pause)
            .unwrap()
            .snapshot
            .phase,
        ControlPhase::Held
    );
    let mut held = [99; 2];
    output(&mut playback_clock, &buffer, &mut held);
    assert_eq!(held, [0; 2]);
    assert_eq!(voice.snapshot(1).submitted_source_frames, Some(0));
    assert_eq!(cue.snapshot(1).submitted_source_frames, Some(0));
    let resume = ControlCommand {
        command_id: uuid::Uuid::from_u128(302),
        sequence: 2,
        action: ControlAction::Resume {
            authorization: ResumeAuthorization {
                kind: ResumeKind::ExplicitContinue,
                detection_id: uuid::Uuid::from_u128(303),
                through_sequence: 0,
            },
        },
        ..pause
    };
    assert_eq!(
        sender
            .apply_control(control, &resume)
            .unwrap()
            .snapshot
            .phase,
        ControlPhase::Running
    );
    let mut resumed = [0; 4];
    output(&mut playback_clock, &buffer, &mut resumed);
    assert_eq!(resumed, [10000, 10000, 20000, 20000]);
    assert_eq!(voice.snapshot(2).submitted_source_frames, Some(2));
    assert_eq!(cue.snapshot(2).submitted_source_frames, Some(0));
    assert!(matches!(
        cue.snapshot(3).observation_end,
        Some(ObservationEnd::Cancelled { .. })
    ));
    capture_clock.probe.close();
    playback_clock.probe.close();
    session.pump(16).unwrap();
    let evidence = round_trip(session);
    let played: Vec<_> = evidence
        .records
        .iter()
        .filter(|r| r.timing.stream.direction == AudioDirection::Playback && r.timing.frames > 0)
        .collect();
    assert_eq!(played.len(), 2);
    assert_eq!(played[0].content, ReferenceContent::HeldSilence);
    assert_eq!(played[0].samples().collect::<Vec<_>>(), [0.0; 2]);
    assert_eq!(played[1].content, ReferenceContent::Media);
    assert_eq!(replay_samples(&evidence, AudioDirection::Playback).len(), 6);
    assert_eq!(
        evidence
            .observed_latest
            .playback
            .as_ref()
            .unwrap()
            .lost_frames,
        0
    );
    cleanup(&sender, &receiver, &mut renderer, &buffer, &[&voice, &cue]);
    assert!(bus.try_claim_reader().unwrap().try_read().is_none());
}

#[test]
fn cancelling_or_dropping_observer_leaves_actual_playback_owner_and_pending_pcm_live() {
    let bus = AudioBus::new(2).reference();
    let cancel = CancellationToken::new();
    let mut session =
        EvidenceSession::start(&bus, EvidenceLimits::default(), cancel.clone()).unwrap();
    let mut capture_clock = stream(&bus, AudioDirection::Capture);
    let mut playback_clock = stream(&bus, AudioDirection::Playback);
    capture(&mut capture_clock, &[8192, -8192]);
    playback_clock.probe.activate();
    session.pump(8).unwrap();
    let (sender, receiver) = channel(8);
    let generation = sender.begin().unwrap();
    let voice = identified(&sender, &receiver, 1, generation);
    submit(&sender, &voice, &[10000, 20000]);
    let mut renderer = Renderer::default();
    let mut buffer = PlaybackBuffer::new(receiver.generation());
    render_pending(&receiver, &mut renderer, &mut buffer);
    let buffer = Mutex::new(buffer);
    cancel.cancel();
    assert_eq!(
        session.pump(8).unwrap(),
        PumpStatus::Stopped(EvidenceEnd::Cancelled)
    );
    let cancelled = round_trip(session);
    assert_eq!(cancelled.end, EvidenceEnd::Cancelled);
    assert!(cancelled.observed_latest.capture.as_ref().unwrap().running);
    assert!(cancelled.observed_latest.playback.as_ref().unwrap().running);
    assert_eq!(voice.snapshot(1).submitted_source_frames, Some(0));
    assert_eq!(voice.snapshot(2).observation_end, None);
    let abandoned =
        EvidenceSession::start(&bus, EvidenceLimits::default(), CancellationToken::new()).unwrap();
    assert!(bus.try_claim_reader().is_none());
    drop(abandoned);
    let mut resumed =
        EvidenceSession::start(&bus, EvidenceLimits::default(), CancellationToken::new()).unwrap();
    capture(&mut capture_clock, &[4096, -4096]);
    let mut played = [0; 4];
    output(&mut playback_clock, &buffer, &mut played);
    assert_eq!(played, [10000, 10000, 20000, 20000]);
    assert_eq!(
        voice.snapshot(3).observation_end,
        Some(ObservationEnd::SubmissionFinished)
    );
    capture_clock.probe.close();
    playback_clock.probe.close();
    resumed.pump(16).unwrap();
    let evidence = round_trip(resumed);
    assert_eq!(
        replay_samples(&evidence, AudioDirection::Capture),
        [0.125, -0.125]
    );
    assert_eq!(
        replay_samples(&evidence, AudioDirection::Playback),
        played.map(|s| f64::from(s) / 32768.0)
    );
    assert_eq!(
        evidence.observed_latest.playback.as_ref().unwrap().cursor,
        2
    );
    cleanup(&sender, &receiver, &mut renderer, &buffer, &[&voice]);
    assert!(bus.try_claim_reader().unwrap().try_read().is_none());
}

#[test]
fn producer_overflow_lost_close_and_reopen_keep_missing_audio_and_old_final_state_unknown() {
    let bus = AudioBus::new(2).reference();
    let mut session =
        EvidenceSession::start(&bus, EvidenceLimits::default(), CancellationToken::new()).unwrap();
    let mut old_capture = stream(&bus, AudioDirection::Capture);
    for _ in 0..80 {
        capture(&mut old_capture, &[8192, -8192]);
    }
    old_capture.probe.close();
    let old_final = bus.snapshot(AudioDirection::Capture).unwrap();
    assert!(old_final.closed);
    assert_eq!(
        (
            old_final.cursor,
            old_final.attempted_blocks,
            old_final.lost_blocks,
            old_final.lost_frames
        ),
        (80, 82, 18, 17)
    );

    let (sender, receiver) = channel(8);
    let generation = sender.begin().unwrap();
    let voice = identified(&sender, &receiver, 1, generation);
    submit(&sender, &voice, &[10000; 10]);
    let mut renderer = Renderer::default();
    let mut buffer = PlaybackBuffer::new(receiver.generation());
    render_pending(&receiver, &mut renderer, &mut buffer);
    let buffer = Mutex::new(buffer);
    let mut playback_clock = stream(&bus, AudioDirection::Playback);
    let mut played = [0; 20];
    output(&mut playback_clock, &buffer, &mut played);
    assert_eq!(played, [10000; 20]);
    assert_eq!(voice.snapshot(1).submitted_source_frames, Some(10));
    playback_clock.probe.close();
    assert_eq!(session.pump(128).unwrap(), PumpStatus::Pumped(64));

    let mut reopened = stream(&bus, AudioDirection::Capture);
    assert_ne!(old_capture.probe.stream_id(), reopened.probe.stream_id());
    capture(&mut reopened, &[4096, -4096]);
    reopened.probe.close();
    session.pump(16).unwrap();
    let evidence = round_trip(session);
    assert_eq!(evidence.records.len(), 67);
    assert!(!evidence.records.iter().any(|r| {
        r.timing.stream == old_final.stream
            && r.discontinuity == Some(AudioDiscontinuity::StreamStopped)
    }));
    let capture_final = evidence.observed_latest.capture.as_ref().unwrap();
    assert!(capture_final.closed);
    assert_ne!(capture_final.stream, old_final.stream);
    assert_eq!(capture_final.cursor, 1);
    // The old closed snapshot was observed above, but replacing a direction
    // does not invent that snapshot or the dropped close marker in the bundle.
    let playback_final = evidence.observed_latest.playback.as_ref().unwrap();
    assert!(playback_final.closed);
    assert_eq!(
        (
            playback_final.cursor,
            playback_final.attempted_blocks,
            playback_final.lost_blocks,
            playback_final.lost_frames
        ),
        (10, 3, 3, 10)
    );
    assert!(replay_samples(&evidence, AudioDirection::Playback).is_empty());
    let replayed = replay_samples(&evidence, AudioDirection::Capture);
    let expected: Vec<_> = std::iter::repeat_n([0.25, -0.25], 63)
        .flatten()
        .chain([0.125, -0.125])
        .collect();
    assert_eq!(replayed, expected);
    assert!(
        evidence
            .replay(EvidenceLimits::default())
            .unwrap()
            .any(|step| {
                step.record.timing.stream == capture_final.stream
                    && step.resets.contains(&ReplayReset::StreamChanged)
            })
    );
    cleanup(&sender, &receiver, &mut renderer, &buffer, &[&voice]);
    assert!(bus.try_claim_reader().unwrap().try_read().is_none());
}
